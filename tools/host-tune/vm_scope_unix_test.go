func TestVMScopeRecoveryApprovalBindsScopeAndDeferral(t *testing.T) {
	dir, _, _, deps := rehearsalFixture(t)
	anchor := convertRetainedFixtureScope(t, dir, tuningScopeVMCPU)
	inputs, err := loadRetainedTuningInputs(dir, anchor)
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	common := []string{"--inputs", dir, "--manifest", anchor, "--scope", tuningScopeVMCPU, "--lab"}
	applied := filepath.Join(root, "applied")
	receipt, err := rehearsalCommand(t, deps, append([]string{"apply"}, append(common, "--maintenance", "--approve", inputs.transaction.IntentSHA256, "--output", applied)...)...)
	if err != nil {
		t.Fatal(err)
	}
	restoration := append(append([]string{}, common...), "--journal", filepath.Join(applied, "journal"), "--journal-sha256", receipt.JournalSHA256, "--purpose", "rollback")
	receipt, err = rehearsalCommand(t, deps, append([]string{"review"}, append(restoration, "--output", filepath.Join(root, "review"))...)...)
	if err != nil || receipt.Review == nil {
		t.Fatalf("%+v %v", receipt, err)
	}
	original := *receipt.Review
	for _, field := range []string{"scope", "nic-verification"} {
		t.Run(field, func(t *testing.T) {
			modified := original
			modified.ApprovalSHA256 = ""
			if field == "scope" {
				modified.Scope = tuningScopeFullHost
			} else {
				modified.NICVerification = "passed"
			}
			data, err := json.Marshal(modified)
			if err != nil {
				t.Fatal(err)
			}
			forged := digest(data)
			if forged == original.ApprovalSHA256 {
				t.Fatal("review did not bind scope declaration")
			}
			output := filepath.Join(t.TempDir(), "restore")
			rejected, err := rehearsalCommand(t, deps, append([]string{"restore"}, append(restoration, "--maintenance", "--approve", forged, "--output", output)...)...)
			if err == nil || rejected.Status != "rejected" {
				t.Fatal("changed scope reused restoration approval")
			}
			checkRehearsalEvidence(t, output)
		})
	}
	restored, err := rehearsalCommand(t, deps, append([]string{"restore"}, append(restoration, "--maintenance", "--approve", original.ApprovalSHA256, "--output", filepath.Join(root, "restored"))...)...)
	if err != nil || restored.Status != "recovery-restored" {
		t.Fatalf("%+v %v", restored, err)
	}
	checkRehearsalEvidence(t, applied)
}
