	if err != nil {
		t.Fatal(err)
	}
	f := newNativeFixture(t)
	f.tx = inputs.transaction
	for i := range f.tx.Changes {
		f.tx.Changes[i].After.UID, f.tx.Changes[i].After.GID = os.Getuid(), os.Getgid()
	}
