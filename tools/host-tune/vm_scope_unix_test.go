func TestVMScopeNativeMandatoryChecksRemainStrict(t *testing.T) {
	for _, mode := range []string{"memory", "cpu", "argv", "exclusion", "foreign-service", "missing-pid"} {
		t.Run(mode, func(t *testing.T) {
			f := vmNativeFixture(t)
			rejectFixtureIRQReads(f)
			command := f.backend.command
			f.backend.command = func(ctx context.Context, args ...string) (string, error) {
				out, err := command(ctx, args...)
				if args[0] == "restart" && args[1] == "bonvoyage.service" {
					v, _ := f.backend.files.Read(ctx, "service-resources")
					if v.Exists {
						switch mode {
						case "memory":
							f.state.MemoryMax = "1"
						case "cpu":
							f.state.CPUs = "0"
						case "argv":
							f.state.Arguments = nativeArguments([]byte("--smp 1 --memory 512M"))
						case "exclusion":
							f.state.IRQBan = ""
						}
					}
				}
				return out, err
			}
			f.badOverride, f.badPID = mode == "foreign-service", mode == "missing-pid"
			outcome, err, _ := runNativeFixture(t, f)
			if err == nil || outcome.Status == "applied" {
				t.Fatal("VM scope weakened required runtime gate")
			}
			for _, path := range nativeControlPaths {
				if _, err := os.Stat(f.root + path); !os.IsNotExist(err) {
					t.Fatal("failed gate left owned control")
				}
			}
		})
	}
}

